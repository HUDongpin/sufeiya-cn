import { readFile, stat } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  MATERIALIZED_LEGACY_RUNTIME_PAIRS,
  findStaleFilePairs,
} from "./generated-currentness.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const generatedModule = join(root, "lib/legacy-content.generated.ts");
let generatedModuleReady = false;
try {
  generatedModuleReady = (await stat(generatedModule)).size > 0
    && (await readFile(generatedModule, "utf8")).startsWith("// Generated by scripts/build-legacy-content.mjs.");
} catch {
  generatedModuleReady = false;
}

const stale = await findStaleFilePairs(root, MATERIALIZED_LEGACY_RUNTIME_PAIRS);
if (!generatedModuleReady || stale.length > 0) {
  throw new Error(
    `Materialized legacy runtime is unavailable: ${[
      ...(!generatedModuleReady ? ["lib/legacy-content.generated.ts"] : []),
      ...stale,
    ].join(", ")}. Run npm run generate:next-content before legacy verification.`,
  );
}

process.stdout.write(
  `PASS check:legacy-runtime (${MATERIALIZED_LEGACY_RUNTIME_PAIRS.length} ignored runtime pairs and generated module)\n`,
);
